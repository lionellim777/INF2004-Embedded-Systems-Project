#!/usr/bin/env python3
"""Mechanical BARR-C:2018 checks for the project-owned C in firmware/app.

This is a subset, not a certification. It checks what a script can check:
80-column lines, tab characters, final newline, unbraced control bodies,
several declarators in one declaration, and a few forbidden constructs.
The remaining rules are reviewed by hand (docs/minimum-bit-representation.md,
section 5). Layout is produced by `clang-format` with the repository's
.clang-format; run it before this script.

Generated pages and upstream copies are not project-owned and are skipped.
Run: py -3 tools/check_barr.py [--list]
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / "firmware" / "app"
SKIP = {
    "calibration_page.h",    # generated from calibration.html
    "measurement_page.h",    # generated page
    "stationary_page.h",     # generated page
    "track_status_codes.h",  # generated by tools/gen_track_status_codes.py
    "dhcpserver.c",          # upstream Pico SDK example
    "dhcpserver.h",
    "lwipopts.h",            # lwIP configuration
    "network_settings.local.h",  # local credentials, never committed
}
FORBIDDEN = re.compile(r"\b(?:auto|register|abort|exit|setjmp|longjmp)\b")
TYPE_START = re.compile(
    r"^\s*(?:static\s+|const\s+|volatile\s+)*"
    r"(?:bool|char|int|unsigned|signed|float|double|uint\d+_t|int\d+_t|size_t)"
    r"\b[^()=;{}]*,[^()=;{}]*;\s*$")


TYPEDEF_MULTI = re.compile(
    r"^\s+[A-Za-z_][A-Za-z0-9_ ]* \*?[a-z_0-9]+(?:\[[^]]*\])?"
    r"(?:, \*?[a-z_0-9]+(?:\[[^]]*\])?)+;\s*$")
WRAPPED_HEAD = re.compile(
    r"^\s+(?:static |const |volatile )*(?:bool|char|int|unsigned"
    r"(?: char| short| int| long)?|float|double|u?int\d+_t|size_t)\s+"
    r"[^()=;{}]*,\s*$")


def strip_literals(line):
    line = re.sub(r'"(?:[^"\\]|\\.)*"', '""', line)
    line = re.sub(r"'(?:[^'\\]|\\.)*'", "''", line)
    return re.sub(r"/\*.*?\*/", "", line)


def unbraced_body(code):
    """True when an if/while/for header closes on this line and a statement
    follows it on the same line without an opening brace."""
    if code.lstrip().startswith("#") or re.search(r"\}\s*while", code):
        return False
    m = re.search(r"\b(?:if|while|for)\s*\(", code)
    if not m:
        return False
    depth = 1
    pos = m.end()
    while pos < len(code) and depth:
        depth += {"(": 1, ")": -1}.get(code[pos], 0)
        pos += 1
    if depth:
        return False  # header continues on the next line
    rest = code[pos:].strip().rstrip("\\").strip()
    return rest not in ("", "{") and not rest.startswith("{") and rest != ";"


def wrapped_decl(lines, index):
    """True when lines[index] starts a declaration of several names that is
    wrapped over lines and ends with ';' (a parameter list ends with ')')."""
    if not WRAPPED_HEAD.match(strip_literals(lines[index])):
        return False
    for follow in lines[index + 1:index + 8]:
        code = strip_literals(follow).split("//")[0]
        if re.search(r"[(){}=]", code):
            return False
        if code.rstrip().endswith(";"):
            return True
    return False


def check(path):
    problems = []
    text = path.read_text(encoding="utf-8")
    all_lines = text.splitlines()
    if not text.endswith("\n"):
        problems.append((0, "missing final newline"))
    in_comment = False
    for number, raw in enumerate(text.splitlines(), 1):
        if len(raw) > 80:
            problems.append((number, "over 80 columns"))
        if "\t" in raw:
            problems.append((number, "tab character"))
        line = raw
        if in_comment:
            if "*/" in line:
                in_comment = False
            continue
        if "/*" in line and "*/" not in line:
            in_comment = True
        code = strip_literals(line).split("//")[0]
        if FORBIDDEN.search(code):
            problems.append((number, "forbidden token"))
        if (TYPE_START.match(code) or wrapped_decl(all_lines, number - 1) or
                (TYPEDEF_MULTI.match(code) and "return" not in code)):
            problems.append((number, "several declarators on one line"))
        if unbraced_body(code):
            problems.append((number, "control body without braces"))
        if re.match(r"^\s*else\s+[^{i\s]", code):
            problems.append((number, "else body without braces"))
    return problems


def main():
    files = sorted(p for p in SOURCES.rglob("*")
                   if p.suffix in (".c", ".h") and p.name not in SKIP)
    total = 0
    by_kind = {}
    for path in files:
        for number, what in check(path):
            total += 1
            by_kind[what] = by_kind.get(what, 0) + 1
            if "--list" in sys.argv:
                print("%s:%d: %s" % (path.relative_to(ROOT), number, what))
    print("%d files checked, %d findings" % (len(files), total))
    for what, count in sorted(by_kind.items()):
        print("  %5d  %s" % (count, what))
    return 1 if total else 0


if __name__ == "__main__":
    sys.exit(main())
