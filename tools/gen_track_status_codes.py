#!/usr/bin/env python3
"""Regenerate firmware/app/mission_rtos/track_status_codes.h.

The track_status MQTT record carries a one-byte code instead of the status text. The code is the
1-based position of the string in this sorted list; 0 means "not in the table". Run after adding a
new course/obstacle/track status string, then rebuild the firmware. The dashboard decoder reads the
same header, so the two cannot drift apart.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / "firmware/app/robot_firmware"
APP = ROOT / "firmware/app/mission_rtos"
SOURCES = [BASE / n for n in (
    "course_control.c", "obstacle_bypass.c", "motion_control.c", "barcode_drive.h", "center_search.h",
    "center_trim.h", "line_check.h", "obstacle_plan.h", "course_control.h")] + [
    APP / n for n in ("track_runtime.c", "motion_runtime.c", "obstacle_io.c", "board.c", "safety_gate.c", "main.c")]
OUT = APP / "track_status_codes.h"
# Substrings the firmware searches for inside a status; they are never reported as a status themselves.
NOT_STATUSES = {"STALL", "ENCODER", "NO_ENCODER_PROGRESS"}
LITERAL = re.compile(r'"([A-Z][A-Z0-9_]{3,})"')


def collect():
    names = set()
    for path in SOURCES:
        names.update(LITERAL.findall(path.read_text(encoding="utf8")))
    return sorted(names - NOT_STATUSES)


def render(names):
    if len(names) > 255:
        raise SystemExit("more than 255 status strings: widen the code or prune the list")
    lines = ["#ifndef RTOS_TRACK_STATUS_CODES_H", "#define RTOS_TRACK_STATUS_CODES_H",
             "/* Generated by tools/gen_track_status_codes.py. One-byte code = 1-based position; 0 = unknown. */",
             "#define TRACK_STATUS_COUNT %du" % len(names), "#define TRACK_STATUS_LIST(X) \\"]
    lines += ["    X(%s) \\" % n for n in names]
    lines[-1] = lines[-1].rstrip(" \\")
    lines.append("#endif")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    names = collect()
    OUT.write_text(render(names), encoding="utf8", newline="\n")
    print("wrote", OUT, len(names), "statuses")
